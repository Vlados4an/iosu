    BEFORE LOGOFF
    ON DATABASE
DECLARE
    v_cnt NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_cnt FROM insurance_contract;
    INSERT INTO EVLAD.LOG3(user_name, activity, contract_cnt)
    VALUES (USER, 'LOGOFF', v_cnt);
END;
