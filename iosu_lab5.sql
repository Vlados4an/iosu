ALTER TABLE insurance_contract
    ADD (
        end_date DATE,
        initial_payment NUMERIC(15, 2)
        );

CREATE OR REPLACE TRIGGER trg_contract_defaults
    BEFORE INSERT
    ON insurance_contract
    FOR EACH ROW
DECLARE
    v_type_name insurance_type.name%TYPE;
    v_coef      NUMBER := 1;
BEGIN
    IF :NEW.contract_date IS NULL THEN
        :NEW.contract_date := SYSDATE;
    END IF;

    :NEW.end_date := :NEW.contract_date + NVL(:NEW.payout_deadline, 365);

    SELECT name
    INTO v_type_name
    FROM insurance_type
    WHERE id = :NEW.insurance_type_id;

    IF v_type_name = 'Жизнь' THEN
        v_coef := 1.5;
    ELSIF v_type_name = 'Авто' THEN
        v_coef := 1.2;
    ELSIF v_type_name = 'Жилье' THEN
        v_coef := 1.3;
    ELSE
        v_coef := 1;
    END IF;

    :NEW.premium := :NEW.premium * v_coef;
    :NEW.initial_payment := :NEW.premium * 0.2;

END;
/


-- 2)Следить за суммами выплат, начислять пеню за просроченные выплаты.
ALTER TABLE payment
    ADD penalty NUMERIC(15, 2);

CREATE OR REPLACE TRIGGER trg_payment_penalty
    BEFORE INSERT OR UPDATE
    ON payment
    FOR EACH ROW
DECLARE
    v_deadline DATE;
BEGIN
    SELECT c.contract_date + c.payout_deadline
    INTO v_deadline
    FROM insurance_contract c
    WHERE c.id = :NEW.insurance_contract_id;

    IF :NEW.payment_date > v_deadline THEN
        :NEW.penalty := (:NEW.amount * 0.01) * (TRUNC(:NEW.payment_date - v_deadline));
    ELSE
        :NEW.penalty := 0;
    END IF;
END;
/

