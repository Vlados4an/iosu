-- Написать DML-триггер, регистрирующий изменение данных (вставку, обновление, удаление) в одной из таблиц БД.
-- Во вспомогательную таблицу LOG1 записывать, кто, когда (дата и время) и какое именно изменение произвел,
-- для одного из столбцов сохранять старые и новые значения писать DML-триггер, регистрирующий изменение
-- данных (вставку, обновление, удаление) в одной из таблиц БД. Во вспомогательную таблицу LOG1 записывать,
-- кто, когда (дата и время) и какое именно изменение произвел, для одного из столбцов сохранять старые и новые значения.

CREATE TABLE LOG1
(
    id          INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    table_name  VARCHAR2(50),
    operation   VARCHAR2(10),
    user_name   VARCHAR2(50),
    change_date TIMESTAMP DEFAULT SYSTIMESTAMP,
    column_name VARCHAR2(50),
    old_value   VARCHAR2(4000),
    new_value   VARCHAR2(4000)
);

CREATE OR REPLACE TRIGGER trg_contract_log
    AFTER INSERT OR UPDATE OR DELETE
    ON insurance_contract
    FOR EACH ROW
BEGIN
    IF INSERTING THEN
        INSERT INTO LOG1(table_name, operation, user_name, column_name, new_value)
        VALUES ('INSURANCE_CONTRACT', 'INSERT', USER, 'CONTRACT_STATUS', :NEW.contract_status);
    ELSIF UPDATING THEN
        INSERT INTO LOG1(table_name, operation, user_name, column_name, old_value, new_value)
        VALUES ('INSURANCE_CONTRACT', 'UPDATE', USER, 'CONTRACT_STATUS', :OLD.contract_status, :NEW.contract_status);
    ELSIF DELETING THEN
        INSERT INTO LOG1(table_name, operation, user_name, column_name, old_value)
        VALUES ('INSURANCE_CONTRACT', 'DELETE', USER, 'CONTRACT_STATUS', :OLD.contract_status);
    END IF;
END;
/


-- Написать DDL-триггер, протоколирующий действия пользователей по
-- созданию, изменению и удалению таблиц в схеме во вспомогательную таблицу
-- LOG2 в определенное время и запрещающий эти действия в другое время.
CREATE TABLE LOG2
(
    id          INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    user_name   VARCHAR2(50),
    operation   VARCHAR2(30),
    object_name VARCHAR2(100),
    log_date    TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE OR REPLACE TRIGGER trg_ddl_log
    AFTER CREATE OR ALTER OR DROP
    ON SCHEMA
DECLARE
    v_hour NUMBER := TO_NUMBER(TO_CHAR(SYSTIMESTAMP AT TIME ZONE 'Europe/Moscow', 'HH24'));
BEGIN
    IF v_hour BETWEEN 9 AND 17 THEN
        INSERT INTO LOG2(user_name, operation, object_name)
        VALUES (SYS_CONTEXT('USERENV', 'SESSION_USER'), ORA_SYSEVENT, ORA_DICT_OBJ_NAME);
    ELSE
        RAISE_APPLICATION_ERROR(-20030, 'DDL-операции разрешены только с 9 до 17');
    END IF;
END;
/

