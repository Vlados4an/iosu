CREATE OR REPLACE TRIGGER trg_payment_penalty
    BEFORE INSERT OR UPDATE
    ON payment
    FOR EACH ROW
DECLARE
    v_deadline DATE;
BEGIN
    SELECT c.contract_date + c.payout_deadline
    INTO v_deadline
    FROM insurance_contract c
    WHERE c.id = :NEW.insurance_contract_id;

    IF :NEW.payment_date > v_deadline THEN
        :NEW.penalty := (:NEW.amount * 0.01) * (TRUNC(:NEW.payment_date - v_deadline));
    ELSE
        :NEW.penalty := 0;
    END IF;
END;
