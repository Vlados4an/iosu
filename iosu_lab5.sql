-- Написать системный триггер, добавляющий запись во вспомогательную
-- таблицу LOG3, когда пользователь подключается или отключается. В таблицу
-- логов записывается имя пользователя (USER), тип активности (LOGON или LOGOFF),
-- дата (SYSDATE), количество записей в основной таблице БД.

CREATE TABLE LOG3
(
    id           INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    user_name    VARCHAR2(50),
    activity     VARCHAR2(10),
    log_date     TIMESTAMP DEFAULT SYSTIMESTAMP,
    contract_cnt NUMBER
);

CREATE OR REPLACE TRIGGER trg_logon
    AFTER LOGON
    ON DATABASE
DECLARE
    v_cnt NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_cnt FROM insurance_contract;
    INSERT INTO EVLAD.LOG3(user_name, activity, contract_cnt)
    VALUES (USER, 'LOGON', v_cnt);
END;
/

